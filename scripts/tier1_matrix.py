"""Render docs/tier1-matrix.md from tier1.yaml + optional batch report(s)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
TIER1 = ROOT / "configs" / "tier1.yaml"


def load_tier1() -> dict:
    return yaml.safe_load(TIER1.read_text(encoding="utf-8")) or {}


def cell(results: dict[str, dict], key: str) -> str:
    entry = results.get(key)
    if not entry:
        return "—"
    if entry.get("ok") is True:
        return "✅"
    if entry.get("ok") is False:
        return "❌"
    return "—"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--report",
        action="append",
        default=[],
        help="batch report.json (repeatable). Filename should contain toolchain-flags hint.",
    )
    ap.add_argument("--out", default=str(ROOT / "docs" / "tier1-matrix.md"))
    args = ap.parse_args()

    data = load_tier1()
    apps = data["apps"]
    matrix = data.get("matrix") or {}
    toolchains = matrix.get("toolchains") or ["clang", "gcc"]
    presets = matrix.get("presets") or ["baseline", "optimize"]

    # Map (toolchain, flags) -> results dict
    buckets: dict[tuple[str, str], dict] = {}
    for path in args.report:
        rep = json.loads(Path(path).read_text(encoding="utf-8"))
        tc = rep.get("toolchain") or "clang"
        fl = rep.get("flags") or "baseline"
        buckets[(tc, fl)] = rep.get("results") or {}

    lines: list[str] = [
        "# SPDX-License-Identifier: Apache-2.0",
        "",
        "# Tier-1 matrix",
        "",
        "Trusted core from [`configs/tier1.yaml`](../configs/tier1.yaml).",
        "Generated by `scripts/tier1_matrix.py`.",
        "",
        "**Legend:** ✅ green · ❌ red · — not run yet",
        "",
    ]

    for tc in toolchains:
        for fl in presets:
            results = buckets.get((tc, fl), {})
            lines.append(f"## {tc} × {fl}")
            lines.append("")
            lines.append("| App | Strength | Result |")
            lines.append("|-----|----------|--------|")
            for a in apps:
                key = f"{a['id']}@{a['version']}"
                strength = a.get("test_strength", "?")
                lines.append(f"| {key} | {strength} | {cell(results, key)} |")
            lines.append("")

    lines.append("## Regenerate")
    lines.append("")
    lines.append("```bash")
    lines.append(
        "python3 scripts/batch_run.py --tier1 --toolchain clang --flags baseline "
        "--skip-perf --report results/batch/tier1-clang-baseline.json"
    )
    lines.append(
        "python3 scripts/tier1_matrix.py "
        "--report results/batch/tier1-clang-baseline.json --out docs/tier1-matrix.md"
    )
    lines.append("```")
    lines.append("")

    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
